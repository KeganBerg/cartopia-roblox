// Plays a scripted session through the web game's real store (src/game/store.ts) and records the
// save after every step into tests/StoreGolden.luau. tests/store.luau plays the same script through
// the transpiled store and expects the same save each time, so the Roblox server's economy is the
// web game's, action for action. The clock and Math.random are pinned so both sides roll the same.
// Usage: node tools/gen-store-golden.mjs <path to the Cartopia web repo>
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { SCRIPT, START, SEED } from './store-script.mjs'

const web = resolve(process.argv[2] ?? '../cartopia')
const out = join(mkdtempSync(join(tmpdir(), 'store-')), 'store.mjs')
execFileSync(join(web, 'node_modules/.bin/esbuild'), [join(web, 'src/game/store.ts'), '--bundle', '--format=esm', '--platform=node', '--log-level=error', `--outfile=${out}`])

let x = SEED
Math.random = () => (x = (x * 16807) % 2147483647) / 2147483647
let now = START
Date.now = () => now
console.warn = () => {}
const S = await import(pathToFileURL(out).href)
const g = S.useGame

// Args can name things in the town by position, since uids differ run to run on other machines.
function arg(a) {
  if (a && typeof a === 'object' && !Array.isArray(a)) {
    const s = g.getState()
    if ('def' in a) return s.buildings.filter((b) => b.def === a.def)[a.i ?? 0]?.uid ?? 'none'
    if ('car' in a) return s.cars[a.car]?.uid ?? 'none'
    if ('goal' in a) return S.activeGoals(s)[a.goal]?.id ?? 'none'
    if ('now' in a) return now
  }
  return a
}
const snapshot = () => {
  const s = g.getState()
  return { save: S.saveOf(s), need: s.need, panel: s.panel, toasts: s.toasts.map((t) => t.text) }
}
const steps = []
for (const step of SCRIPT) {
  now += step.wait ?? 0
  const args = (step.args ?? []).map(arg)
  const result = g.getState()[step.do](...args)
  steps.push({ ...snapshot(), result: result ?? null })
  g.setState({ toasts: [] })
}

const ident = /^[A-Za-z_][A-Za-z0-9_]*$/
const str = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"'
function lua(v) {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'string') return str(v)
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : v > 0 ? 'math.huge' : '-math.huge'
  if (typeof v === 'boolean') return String(v)
  if (Array.isArray(v)) return `{ ${v.map(lua).join(', ')} }`
  const e = Object.entries(v).filter(([, x]) => x !== undefined)
  return `{ ${e.map(([k, x]) => `${ident.test(k) ? k : `[${str(k)}]`} = ${lua(x)}`).join(', ')} }`
}
writeFileSync(new URL('../tests/StoreGolden.luau', import.meta.url), [
  '--!nocheck',
  '-- GENERATED by tools/gen-store-golden.mjs: the web store\'s state after each step of tools/store-script.mjs.',
  '',
  'local NULL = require("./Null")',
  '',
  'return {',
  `\tstart = ${START},`,
  `\tseed = ${SEED},`,
  `\tsteps = {`,
  ...SCRIPT.map((step, i) => `\t\t{ ["do"] = ${str(step.do)}, wait = ${step.wait ?? 0}, args = ${lua(step.args ?? [])}, expect = ${lua(steps[i])} },`),
  '\t},',
  '}',
  '',
].join('\n'))
console.log(`recorded ${steps.length} steps`)
