// Regenerates src/shared/Catalog.luau from the web game's src/game/data.ts.
// Usage: node tools/gen-catalog.mjs <path to the Cartopia web repo>
// Needs that repo's node_modules (npm ci) for esbuild.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const web = resolve(process.argv[2] ?? '../cartopia')
const out = join(mkdtempSync(join(tmpdir(), 'catalog-')), 'data.mjs')
execFileSync(join(web, 'node_modules/.bin/esbuild'), [join(web, 'src/game/data.ts'), '--bundle', '--format=esm', '--platform=node', `--outfile=${out}`])
const data = await import(pathToFileURL(out).href)

// Static tables only: functions are ported by hand in Data.luau. Task pools carry an `n`
// function per task, which is dropped here and lives in Data.luau's TASK_COUNTS.
const TYPES = {
  BUILDINGS: '{T.BuildingDef}', CARS: '{T.CarDef}', MODS: '{T.ModDef}', SKINS: '{T.SkinDef}', MOD_SKINS: '{T.SkinDef}',
  CAMPAIGN: '{T.CampaignChapter}', GP_SERIES: '{T.GpSeries}', CAR_SETS: '{T.CarSet}', RESCUE_SPOTS: '{T.RescueSpot}',
  GOALS: '{T.GoalDef}', DAILY_TASKS: '{T.TaskDef}', WEEKLY_TASKS: '{T.TaskDef}', DEALS: '{T.DealDef}', EVENTS: '{T.GameEvent}',
  DEAL_SLOTS: '{ { name: string, step: number, deals: {T.DealDef} } }',
  PAINTS: '{ { color: string, name: string, bucks: number? } }',
  STRIPES: '{ string | false }',
  DAILY_BONUS: '{ { coins: number, fuel: number?, parts: number?, bucks: number? } }',
  SEASON_TIERS: '{ { coins: number, parts: number, bucks: number, car: boolean? } }',
  BUCKS_PACKS: '{ { id: string, name: string, price: number, bucks: number, bonus: number, coins: number?, parts: number?, tag: string?, art: string } }',
}

const ident = /^[A-Za-z_][A-Za-z0-9_]*$/
const RESERVED = new Set(['and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while', 'continue', 'type', 'export'])
const str = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"'
const key = (k) => (ident.test(k) && !RESERVED.has(k) ? k : `[${str(k)}]`)
function lua(v, indent = '') {
  if (v === null) return 'false' // only STRIPES has one: "no stripe"
  if (typeof v === 'string') return str(v)
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error('non-finite number')
    return String(v)
  }
  if (typeof v === 'boolean') return String(v)
  const inner = indent + '\t'
  if (Array.isArray(v)) {
    const parts = v.map((x) => lua(x, inner))
    const flat = `{ ${parts.join(', ')} }`
    if (flat.length < 100 && !flat.includes('\n')) return v.length ? flat : '{}'
    return `{\n${parts.map((p) => inner + p + ',').join('\n')}\n${indent}}`
  }
  const entries = Object.entries(v).filter(([, x]) => x !== undefined && typeof x !== 'function')
  if (!entries.length) return '{}'
  const parts = entries.map(([k, x]) => `${key(k)} = ${lua(x, inner)}`)
  const flat = `{ ${parts.join(', ')} }`
  if (flat.length < 140 && !flat.includes('\n')) return flat
  return `{\n${parts.map((p) => inner + p + ',').join('\n')}\n${indent}}`
}

const lines = [
  '--!strict',
  '-- GENERATED by tools/gen-catalog.mjs from the web game\'s src/game/data.ts. Do not edit by hand:',
  '-- change data.ts and regenerate, so the web and Roblox catalogs stay identical.',
  '',
  'local T = require("./Types")',
  '',
  'local Catalog = {}',
  '',
]
for (const [k, v] of Object.entries(data).sort(([a], [b]) => a.localeCompare(b))) {
  if (typeof v === 'function') continue
  const body = lua(v)
  lines.push(`Catalog.${k} = ${TYPES[k] ? `(${body} :: ${TYPES[k]})` : body}`)
}
lines.push('', 'return Catalog', '')
const dest = new URL('../src/shared/Catalog.luau', import.meta.url)
writeFileSync(dest, lines.join('\n'))
console.log('wrote', dest.pathname)

// The referee's fastest allowed finish time per PI, from the newest migration that sets
// public.race_floor() (the web repo's race.test.ts checks it against race.ts). Computing one in
// Luau takes about a second, so Race.raceFloor reads this table first.
const migrations = join(web, 'supabase/migrations')
const sql = readdirSync(migrations).sort().map((f) => readFileSync(join(migrations, f), 'utf8')).filter((s) => s.includes('$floors$')).pop()
const floors = JSON.parse(/\$floors\$(.*)\$floors\$/s.exec(sql)[1])
const rows = []
for (let i = 0; i < floors.length; i += 10) rows.push('\t' + floors.slice(i, i + 10).join(', ') + ',')
const floorsDest = new URL('../src/shared/RaceFloors.luau', import.meta.url)
writeFileSync(floorsDest, [
  '--!strict',
  '-- GENERATED by tools/gen-catalog.mjs from the web game\'s race_floor() migration. Index = PI.',
  '-- The fastest finish time (seconds) the race referee accepts for a car with that PI.',
  '',
  'return {',
  ...rows,
  '}',
  '',
].join('\n'))
console.log('wrote', floorsDest.pathname)
