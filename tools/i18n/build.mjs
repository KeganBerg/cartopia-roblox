// Converts the web game's language dictionaries (src/i18n/es.json, pt.json) into Luau modules for
// client/Lang (src/shared/I18n/<lang>.luau, generated: never hand-edit). Run by transpile.mjs, or
// on its own: node tools/i18n/build.mjs <web repo>.
//
// As the web's src/i18n/translate.ts compile(): a line with no gap is an exact match; a line with
// `{}` or a lone `#` becomes a pattern (here a Lua pattern, the gaps as captures), filed under its
// longest word so a text is only tried against patterns that share a word with it.
import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const GAP = /\{\}|(?<=^|\s)#(?=\s|$|[.,!?:;)])/g
const words = (s) => s.toLowerCase().match(/[a-z]{3,}/g) ?? []
const luaPat = (s) => s.replace(/[\^$()%.[\]*+\-?]/g, '%$&')
// A Luau string literal (the text kept as UTF-8; only quotes, backslashes and control characters escaped).
const lit = (s) => '"' + s.replace(/[\\"]/g, '\\$&').replace(/[\x00-\x1f]/g, (c) => ({ '\n': '\\n', '\r': '\\r', '\t': '\\t' })[c] ?? `\\${c.charCodeAt(0)}`) + '"'

export function buildI18n(web) {
  const out = join(root, 'src/shared/I18n')
  mkdirSync(out, { recursive: true })
  const langs = []
  for (const lang of ['es', 'pt']) {
    const file = join(web, 'src/i18n', `${lang}.json`)
    if (!existsSync(file)) continue
    const dict = JSON.parse(readFileSync(file, 'utf8'))
    const exact = []
    const pats = []
    for (const [en, to] of Object.entries(dict)) {
      if (!to || to === en) continue
      GAP.lastIndex = 0
      if (!GAP.test(en)) {
        exact.push(`\t[${lit(en)}] = ${lit(to)},`)
        continue
      }
      GAP.lastIndex = 0
      const parts = en.split(GAP)
      const key = parts.flatMap(words).sort((a, b) => b.length - a.length)[0] ?? ''
      pats.push(`\t{ ${lit(key)}, ${lit('^' + parts.map(luaPat).join('(.-)') + '$')}, ${lit(to)} },`)
    }
    // In parts of at most 1,200 lines each: Roblox scripts are kept well under 200,000 characters.
    const dir = join(out, lang)
    rmSync(dir, { recursive: true, force: true })
    mkdirSync(dir, { recursive: true })
    const head = (what) => ['--!nocheck', `-- GENERATED by tools/i18n/build.mjs from the web game's src/i18n/${lang}.json. Do not edit.`, what]
    const parts = []
    for (let i = 0; i < exact.length; i += 1200) parts.push(exact.slice(i, i + 1200))
    parts.forEach((p, i) => writeFileSync(join(dir, `exact${i + 1}.luau`), [...head('-- English -> translation.'), 'return {', ...p, '}', ''].join('\n')))
    writeFileSync(join(dir, 'pats.luau'), [...head('-- { longest word ("" for none), Lua pattern, translation }.'), 'return {', ...pats, '}', ''].join('\n'))
    const dest = dir
    langs.push(`${relative(root, dest)} (${exact.length} lines, ${pats.length} patterns)`)
  }
  return langs
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const l of buildI18n(process.argv[2] ?? '../Cartopia')) console.log(`wrote ${l}`)
}
