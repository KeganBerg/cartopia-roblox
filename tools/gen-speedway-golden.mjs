// Regenerates tests/SpeedwayGolden.luau: where the web game's Speedway crowd (scene/speedwayCrowd.ts,
// with the real three.js) puts its seats, fans and arms. tests/speedway.luau runs the converted
// module (Shared.Game.scene_speedwayCrowd, on the three.js stand-in) with the same inputs and
// expects the same answers.
// Usage: node tools/gen-speedway-golden.mjs <path to the Cartopia web repo>
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const web = resolve(process.argv[2] ?? '../cartopia')
const dir = mkdtempSync(join(tmpdir(), 'speedway-golden-'))
const out = join(dir, 'crowd.mjs')
execFileSync(join(web, 'node_modules/.bin/esbuild'), [join(web, 'src/scene/speedwayCrowd.ts'), '--bundle', '--format=esm', '--platform=node', `--outfile=${out}`])
const C = await import(pathToFileURL(out).href)

const r = (x) => Math.round(x * 1e9) / 1e9
const stands = []
for (const k of [1, 2]) {
  for (let lvl = 1; lvl <= 10; lvl++) {
    const { seats, aisles, fans } = C.speedwayStands(lvl, k)
    // A few seats' transforms (first, middle, last, and the first of the upper deck when there is one).
    const pick = [...new Set([0, seats.length >> 1, seats.length - 1, seats.findIndex((s) => s.row === 3)])].filter((i) => i >= 0)
    stands.push({
      lvl, k, seats: seats.length, aisles: aisles.length, fans,
      rows: [...new Set(seats.map((s) => s.row))].length,
      picks: pick.map((i) => ({ i, a: r(seats[i].a), r: r(seats[i].r), y: r(seats[i].y), row: seats[i].row, m: Array.from(C.seatMatrix(seats[i], 1, 1).elements, r) })),
    })
  }
}
const arms = []
for (const side of [-1, 1]) for (const cheer of [0, 0.5, 1]) for (const wave of [-1, 0, 0.3, 1]) arms.push({ side, cheer, wave, m: Array.from(C.armMatrix(side, cheer, wave).elements, r) })

const lua = (v) => {
  if (Array.isArray(v)) return `{ ${v.map(lua).join(', ')} }`
  if (v && typeof v === 'object') return `{ ${Object.entries(v).map(([k, x]) => `${k} = ${lua(x)}`).join(', ')} }`
  return String(v)
}
writeFileSync(resolve('tests/SpeedwayGolden.luau'), [
  '--!nocheck',
  '-- GENERATED by tools/gen-speedway-golden.mjs from the web game\'s scene/speedwayCrowd.ts. Do not edit.',
  'return {',
  `\tstands = {\n${stands.map((s) => `\t\t${lua(s)},`).join('\n')}\n\t},`,
  `\tarms = {\n${arms.map((a) => `\t\t${lua(a)},`).join('\n')}\n\t},`,
  `\tBODY = ${lua(C.BODY)},`,
  `\tSEAT_IN = ${C.SEAT_IN},`,
  `\tFAN = ${C.FAN},`,
  '}',
  '',
].join('\n'))
console.log(`wrote tests/SpeedwayGolden.luau (${stands.length} stands, ${arms.length} arms)`)
