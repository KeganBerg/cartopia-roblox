// Regenerates tests/CentresGolden.luau: where the web game lays out its Big Bison travel stop and
// Bubble Car Spa (src/game/travelCenter.ts, src/game/washCenter.ts, and WashCenter.tsx's doorAt) for
// every block shape. tests/centres.luau runs the hand copy (src/shared/CentreLayout.luau) with the
// same inputs and expects the same answers.
// Usage: node tools/gen-centres-golden.mjs <path to the Cartopia web repo>
//
// The two layout files only need TILE and growthStage from the rest of the game, so they're copied
// on their own with those two stubbed, and run with Node's own TypeScript stripping (no install).
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const web = resolve(process.argv[2] ?? '../cartopia')
const dir = mkdtempSync(join(tmpdir(), 'centres-golden-'))
writeFileSync(join(dir, 'data.ts'), 'export const TILE = 2\n')
writeFileSync(join(dir, 'growth.ts'), 'export const growthStage = (level: number) => (level >= 7 ? 3 : level >= 4 ? 2 : 1)\n')
for (const f of ['travelCenter.ts', 'washCenter.ts']) {
  const src = readFileSync(join(web, 'src/game', f), 'utf8').replace(/from '\.\/(data|growth)'/g, "from './$1.ts'")
  writeFileSync(join(dir, f), src)
}
// doorAt lives in the scene file, next to React: copy just the function.
const scene = readFileSync(join(web, 'src/scene/WashCenter.tsx'), 'utf8')
const doorAt = scene.slice(scene.indexOf('function doorAt'), scene.indexOf('\n}\n', scene.indexOf('function doorAt')) + 3)
writeFileSync(join(dir, 'doorAt.ts'), `import type { WashLayout } from './washCenter.ts'\nexport ${doorAt}`)
writeFileSync(join(dir, 'main.ts'), `
import { travelLayout } from './travelCenter.ts'
import { washLayout } from './washCenter.ts'
import { doorAt } from './doorAt.ts'
const shapes = [[2, 2], [2, 1], [1, 2], [4, 4]]
const out = { travel: [], wash: [] }
for (const [sx, sz] of shapes) {
  out.travel.push({ sx, sz, t: travelLayout(sx, sz) })
  const w = washLayout(sx, sz)
  out.wash.push({ sx, sz, t: w, door: doorAt(w) })
}
console.log(JSON.stringify(out))
`)
const data = JSON.parse(execFileSync(process.execPath, ['--experimental-strip-types', '--no-warnings', join(dir, 'main.ts')], { encoding: 'utf8' }))

const r = (x) => Math.round(x * 1e9) / 1e9
const lua = (v) => {
  if (v === null) return 'nil'
  if (Array.isArray(v)) return `{ ${v.map(lua).join(', ')} }`
  if (v && typeof v === 'object') return `{ ${Object.entries(v).map(([k, x]) => `${k} = ${lua(x)}`).join(', ')} }`
  if (typeof v === 'number') return String(r(v))
  return String(v)
}
writeFileSync(resolve('tests/CentresGolden.luau'), [
  '--!nocheck',
  '-- Generated by tools/gen-centres-golden.mjs from the web game: do not edit.',
  `return ${lua(data)}`,
  '',
].join('\n'))
console.log('wrote tests/CentresGolden.luau')
